#!/usr/bin/env python3
"""Simple AI assistant that can call local Python tools during chat."""

# Standard-library import: environment variables are needed to read config values.
import os

# Third-party libraries: dotenv loads settings from a local .env file and OpenAI provides the client.
from dotenv import load_dotenv
from openai import OpenAI
from types import SimpleNamespace

# Local project modules: available tools and shared logging helpers.
from tools import TOOLS, run_tool
from utilities.utilities import log

# Load local configuration from .env so connection details stay out of source code.
load_dotenv()

# Keep tool-calling loops under control so the bot doesn't recurse forever.
MAX_RUN_STEPS = 3

# Build the OpenAI client using your endpoint and API key from the environment.
# This gives all requests a consistent connection to the model provider.
client = OpenAI(
    base_url=os.getenv("BASE_URL"),
    api_key=os.getenv("API_KEY"),
)

# Store the conversation history so each new message can be sent with earlier context.
messages = []

# Configure the assistant's default personality and response rules.
# This system prompt shapes tone, style, and how often tools are used.
messages.append(
    {
        "role": "system",
        "content": (
            "You are helpful, humble assistant. "
            "Answer general questions (programming, science, advice) from your own knowledge."
            "Use a tool ONLY when the user asks for the current time, the weather, or their city."
            "Keep answers under 100 words"
        )
    }
)


# Stream a chat response and collect both plain text and any tool calls generated by the model.
def stream_chat(history):
    stream = client.chat.completions.create(
        model=os.getenv("MODEL"),
        messages=history,
        tools=TOOLS,
        stream=True,
    )

    full_response = ""
    calls = {}
    label_printed = False

    # Process each streamed chunk from the model.
    try:
        for chunck in stream:
            if not chunck.choices:
                continue

            delta = chunck.choices[0].delta

            # 1) Print normal textual output as it arrives from the model.
            if delta.content:
                if not label_printed:
                    print(" Assitance: ", end="", flush=True)
                    label_printed = True
                print(delta.content, end="", flush=True)
                full_response = full_response + delta.content

            # 2) Capture streamed tool-call fragments and merge them by tool index.
            # This is necessary because OpenAI may send a function name or arguments in multiple chunks.
            for tc in (delta.tool_calls or []):
                obj = calls.setdefault(
                    tc.index,
                    SimpleNamespace(
                        id=None,
                        function=SimpleNamespace(
                            name="",
                            arguments=""
                        )
                    )
                )
                if tc.id:
                    obj.id = tc.id
                if tc.function and tc.function.name:
                    obj.function.name = obj.function.name + tc.function.name
                if tc.function and tc.function.arguments:
                    obj.function.arguments = obj.function.arguments + tc.function.arguments
    except KeyboardInterrupt:
        # Allow the user to stop the stream cleanly without crashing the app.
        print("\n Stopped by you!!")
        calls = {}

    if label_printed:
        print()  # Move to the next line after the assistant's response.

    # Convert the dictionary of tool calls to a list in sorted order.
    calls_list = []
    for key in sorted(calls):
        calls_list.append(calls[key])

    return full_response, calls_list


# Turn the collected tool call objects into the exact format the OpenAI API expects.
def build_tool_calls_payload(tool_calls):
    """
    Convert the collected tool calls into the dict format expected inside an assistant message.
    """
    payload = []
    for tool_call in tool_calls:
        tool_call_dict = {
            "id": tool_call.id,
            "type": "function",
            "function": {
                "name": tool_call.function.name,
                "arguments": tool_call.function.arguments,
            }
        }
        payload.append(tool_call_dict)

    return payload


# Main chat loop: keep reading input until the user exits, while handling model tool requests.
while True:
    user_input = input("\n🙋🏻RESHMA_SHAIK: ")

    # Quit the app cleanly on common exit commands.
    if user_input.lower() in ["exit", "quit", "bye", "goodbye"]:
        break

    # Add the user's message to the conversation before sending it to the model.
    messages.append({"role": "user", "content": user_input})

    for step in range(MAX_RUN_STEPS):
        full_response, tool_calls = stream_chat(messages)

        # If no tool call was requested, the model already produced a final answer.
        if not tool_calls:
            break

        log(f"Step {step + 1}: model requested {len(tool_calls)} tool call(s)")

        # Send the assistant message back with tool requests so the API can match results later.
        messages.append({
            "role": "assistant",
            "content": full_response,
            "tool_calls": build_tool_calls_payload(tool_calls)
        })

        # Run every requested tool and pass the result back into the conversation as a tool message.
        for tool_call in tool_calls:
            result = run_tool(tool_call)
            messages.append(
                {
                    "role": "tool",
                    "tool_id": tool_call.id,
                    "content": str(result),
                }
            )
    else:
        # This branch runs only if the model keeps requesting tools past the safe step limit.
        fallback = "I couldn't complete your request within the allowed steps. Please try again."
        messages.append({
            "role": "assistant",
            "content": fallback,
        })
        print("ASSISTANT: " + fallback)
        continue
